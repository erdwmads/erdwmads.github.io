import * as THREE from 'three';
import {Brush,Evaluator,SUBTRACTION,INTERSECTION} from 'three-bvh-csg';
import {ImprovedNoise} from 'three/addons/math/ImprovedNoise.js';
import {writeFile} from 'node:fs/promises';

// Offline conceptual geometry. This is not a reconstructed parent or a fracture solver.
const noise=new ImprovedNoise(),evaluate=new Evaluator();
evaluate.attributes=['position','normal'];
const exterior=new THREE.MeshBasicMaterial(),interior=new THREE.MeshBasicMaterial(),pore=new THREE.MeshBasicMaterial();
const geometry=new THREE.IcosahedronGeometry(1,15),positions=geometry.attributes.position;
for(let i=0;i<positions.count;i++) {
  const p=new THREE.Vector3().fromBufferAttribute(positions,i).normalize();
  const radius=1+.14*noise.noise(p.x*2.1,p.y*2.1,p.z*2.1)+.065*noise.noise(p.x*5,p.y*5,p.z*5)+.014*noise.noise(p.x*24,p.y*24,p.z*24);
  positions.setXYZ(i,p.x*radius,p.y*radius*.91,p.z*radius);
}
// Preserve the smooth exterior normal field; cut surfaces receive their own normals.
let parent=new Brush(geometry,exterior);parent.updateMatrixWorld();
const cavities=[
  {at:[.04,.12,.22],scale:[.31,.24,.35]},
  {at:[-.29,-.25,.15],scale:[.23,.17,.24]},
  {at:[.37,.38,.20],scale:[.18,.20,.23]},
  {at:[-.20,.45,-.03],scale:[.12,.14,.16]}
];
for(const {at,scale} of cavities) {
  const g=new THREE.IcosahedronGeometry(1,4),p=g.attributes.position;
  for(let i=0;i<p.count;i++) {const v=new THREE.Vector3().fromBufferAttribute(p,i);v.multiplyScalar(1+.08*noise.noise(v.x*4,v.y*4,v.z*4));p.setXYZ(i,...v.toArray());}
  const cut=new Brush(g,pore);cut.position.fromArray(at);cut.scale.fromArray(scale);cut.updateMatrixWorld();
  parent=evaluate.evaluate(parent,cut,SUBTRACTION);parent.updateMatrixWorld();
}
const sites=[[-.53,-.40,-.30],[.22,-.58,-.30],[.61,-.09,-.34],[-.44,.28,-.48],[.13,.34,-.42],[.50,.55,-.08],[-.68,.01,.22],[-.23,-.61,.39],[.39,-.33,.51],[-.33,.52,.38],[.12,.15,.66],[.59,.20,.40]].map(p=>new THREE.Vector3(...p));
const chunks=[];
for(let i=0;i<sites.length;i++) {
  let piece=parent;
  for(let j=0;j<sites.length;j++)if(i!==j) {
    const normal=sites[j].clone().sub(sites[i]).normalize(),mid=sites[j].clone().add(sites[i]).multiplyScalar(.5);
    const half=new Brush(new THREE.BoxGeometry(8,8,8),interior);
    half.quaternion.setFromUnitVectors(new THREE.Vector3(0,0,1),normal);half.position.copy(mid).addScaledVector(normal,-4);half.updateMatrixWorld();
    piece=evaluate.evaluate(piece,half,INTERSECTION);piece.updateMatrixWorld();
  }
  const g=piece.geometry,index=g.index,p=g.attributes.position,n=g.attributes.normal;
  const attributes=[],indices=[],kinds=[],lookup=new Map();
  const materials=Array.isArray(piece.material)?piece.material:[piece.material];
  const limit=Math.min(g.drawRange.start+g.drawRange.count,index?.count??p.count);
  function warp(v) {
    const amount=.012*noise.noise(v.x*7,v.y*7,v.z*7)+.003*noise.noise(v.x*29,v.y*29,v.z*29);
    return v.clone().add(new THREE.Vector3(amount*.65,amount*.47,amount));
  }
  function emit(points,normals,kind,level=0) {
    const lengths=points.map((a,i)=>a.distanceToSquared(points[(i+1)%3]));
    const edge=lengths.indexOf(Math.max(...lengths));
    if(kind!==0&&lengths[edge]>.018&&level<7) {
      const a=edge,b=(edge+1)%3,c=(edge+2)%3,mid=points[a].clone().add(points[b]).multiplyScalar(.5),normal=normals[a].clone().add(normals[b]).normalize();
      emit([points[a],mid,points[c]],[normals[a],normal,normals[c]],kind,level+1);
      emit([mid,points[b],points[c]],[normal,normals[b],normals[c]],kind,level+1);return;
    }
    const warped=points.map(warp),normal=new THREE.Triangle(...warped).getNormal(new THREE.Vector3());
    for(let k=0;k<3;k++) {
      const values=[...warped[k].toArray(),...(kind===1?normal:normals[k]).toArray()].map(v=>Math.round(v*10000));
      const key=values.join(',')+','+kind;
      if(!lookup.has(key)){lookup.set(key,attributes.length/6);attributes.push(...values);}
      indices.push(lookup.get(key));
    }
    kinds.push(kind);
  }
  for(let start=g.drawRange.start;start<limit;start+=3) {
    const group=g.groups.find(group=>start>=group.start&&start<group.start+group.count),mat=materials[group?.materialIndex??0];
    const kind=mat===exterior?0:mat===pore?2:1;
    const ids=[0,1,2].map(k=>index?index.getX(start+k):start+k);
    emit(ids.map(id=>new THREE.Vector3().fromBufferAttribute(p,id)),ids.map(id=>new THREE.Vector3().fromBufferAttribute(n,id)),kind);
  }
  chunks.push({vertices:attributes,indices,kinds});
  console.log(`Piece ${i+1}: ${attributes.length/6} vertices, ${indices.length/3} triangles`);
}
await writeFile(new URL('../src/scripts/origins-volume-data.js',import.meta.url),`// Generated by scripts/generate-origins-volume.mjs; conceptual, not measured.\nexport const originVolume=${JSON.stringify({cavities,chunks})};\n`);
